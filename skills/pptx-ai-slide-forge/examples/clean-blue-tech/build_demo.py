def RGB(h):
    return RGBColor.from_string(h)


def style_run(run, text, pt, color, bold=False):
    run.text = text
    f = run.font
    f.name, f.size, f.bold = FONT, Pt(pt), bold
    f.color.rgb = RGB(color)


def txt(slide, x, y, w, h, paras, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(IN(x), IN(y), IN(w), IN(h))
    tf = box.text_frame
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    tf.vertical_anchor = anchor
    for m in ("margin_left", "margin_right", "margin_top", "margin_bottom"):
        setattr(tf, m, 0)
    for i, p in enumerate(paras):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        para.alignment = p.get("align", PP_ALIGN.LEFT)
        para.line_spacing = p.get("ls", 1.2)
        for r in p["runs"]:
            style_run(para.add_run(), r[0], r[1], r[2], r[3] if len(r) > 3 else False)
    return box


def set_fill_alpha(shp, pct):
    sf = shp._element.spPr.find(
        "{http://schemas.openxmlformats.org/drawingml/2006/main}solidFill")
    clr = sf.find("{http://schemas.openxmlformats.org/drawingml/2006/main}srgbClr")
    clr.append(clr.makeelement(
        "{http://schemas.openxmlformats.org/drawingml/2006/main}alpha",
        {"val": str(int(pct * 1000))}))


def shape(slide, kind, x, y, w, h, fill=None, line=None, line_w=0.75):
    shp = slide.shapes.add_shape(kind, IN(x), IN(y), IN(w), IN(h))
    if fill:
        shp.fill.solid()
        shp.fill.fore_color.rgb = RGB(fill)
    else:
        shp.fill.background()
    if line:
        shp.line.color.rgb = RGB(line)
        shp.line.width = Pt(line_w)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def gradient_fill(shp, c1, c2, angle=45.0):
    shp.fill.gradient()
    stops = shp.fill.gradient_stops
    stops[0].color.rgb = RGB(c1)
    stops[0].position = 0.0
    stops[1].color.rgb = RGB(c2)
    stops[1].position = 1.0
    try:
        shp.fill.gradient_angle = angle
    except Exception:
        pass


def rect(slide, x, y, w, h, fill, line=None, line_w=0.75):
    return shape(slide, MSO_SHAPE.RECTANGLE, x, y, w, h, fill=fill, line=line,
                 line_w=line_w)


def oval(slide, x, y, w, h=None, fill=None, line=None, line_w=0.75):
    return shape(slide, MSO_SHAPE.OVAL, x, y, w, h or w, fill=fill, line=line,
                 line_w=line_w)


def conn(slide, x1, y1, x2, y2, color=PRIMARY, line_w=0.75):
    c = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, IN(x1), IN(y1), IN(x2), IN(y2))
    c.line.color.rgb = RGB(color)
    c.line.width = Pt(line_w)
    return c


def marker(slide, x, y, d=0.18, color=PRIMARY):
    shape(slide, MSO_SHAPE.RECTANGLE, x, y, d, d, fill=color)


def plus(slide, x, y, d=0.16, color=PRIMARY):
    shape(slide, MSO_SHAPE.RECTANGLE, x, y + d / 2 - 0.015, d, 0.03, fill=color)
    shape(slide, MSO_SHAPE.RECTANGLE, x + d / 2 - 0.015, y, 0.03, d, fill=color)


def brand(slide, label, page=None, on_blue=False):
    marker(slide, ML, 0.5, 0.18, color=WHITE if on_blue else PRIMARY)
    txt_col = WHITE if on_blue else TEXT
