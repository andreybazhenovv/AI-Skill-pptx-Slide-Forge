"""pptx-ai-slide-forge :: 3-slide EN demo in the Clean Blue Tech style
(light corporate: white backgrounds, royal-blue accents, isometric vector
diagrams - floating platform stack with 3D depth, soft-shadow cards,
radial network map).

Backgrounds are generated by the liquid engine in light mode - pale blue
washes with defined silk bands and dot fields (see textures_config.py).

Block primitives: iso_platform (top face + front edge + soft shadow),
soft_card (white fill + thin border + shadow), network_map (orbit ring +
center node + satellites + connectors + status capsules).

Run from this directory:
    python3 ../../scripts/make_textures.py --config textures_config.py
    python3 build_demo.py
    bash ../../scripts/render_qa.sh "$PWD/clean-blue-tech.pptx" qa
"""
