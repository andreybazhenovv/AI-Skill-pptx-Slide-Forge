issues, sw, sh = [], prs.slide_width, prs.slide_height
for idx, slide in enumerate(prs.slides, start=1):
    boxes = []
    for shp in slide.shapes:
        if shp.left is None:
            continue
        # text boxes must stay in bounds; decorative shapes may bleed 1 in off-slide
        has_text = shp.has_text_frame and shp.text_frame.text.strip()
        tol = 1000 if has_text else 3_600_000
        if shp.left < -tol or shp.top < -tol or shp.left + shp.width > sw + tol \
                or shp.top + shp.height > sh + tol:
            issues.append(f"slide {idx}: out of bounds ({shp.shape_type}, "
                          f"pos {shp.left / EMU_IN:.2f},{shp.top / EMU_IN:.2f})")
        if shp.has_text_frame and shp.text_frame.text.strip():
            boxes.append((shp.left, shp.top, shp.width, shp.height, shp.text_frame.text[:24]))
    for i in range(len(boxes)):
        for j in range(i + 1, len(boxes)):
            a, b = boxes[i], boxes[j]
            ix = max(0, min(a[0] + a[2], b[0] + b[2]) - max(a[0], b[0]))
            iy = max(0, min(a[1] + a[3], b[1] + b[3]) - max(a[1], b[1]))
            if (ix / EMU_IN) * (iy / EMU_IN) > 0.05:
                issues.append(f"slide {idx}: overlap \u00ab{a[4]}\u00bb \u00d7 \u00ab{b[4]}\u00bb")
print("geometry:", issues if issues else "clean")
