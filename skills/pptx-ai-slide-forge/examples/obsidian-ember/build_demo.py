"""pptx-ai-slide-forge :: 3-slide EN demo in the Obsidian Ember style
(industrial editorial: near-black/burgundy, molten orange highlights,
uppercase extra-bold typography, before/after workflow comparison).

Backgrounds are generated by the liquid engine with the ember palette
(see textures_config.py in this directory).

Run from this directory:
    python3 ../../scripts/make_textures.py --config textures_config.py
    python3 build_demo.py
    bash ../../scripts/render_qa.sh "$PWD/obsidian-ember.pptx" qa
"""
import os

from pptx import Presentation
from pptx.util import Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR, MSO_AUTO_SIZE
from pptx.enum.shapes import MSO_SHAPE

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "assets")
OUT = os.path.join(HERE, "obsidian-ember.pptx")
EMU_IN = 914400


def IN(v):
    return Emu(int(round(v * EMU_IN)))


# ---- Obsidian Ember tokens ----
BLACK, BURGUNDY, PLUM = "050505", "300015", "47001D"
BURNT, EMBER, ORANGE, HOT = "8E1015", "E32820", "F05A12", "FF6A00"
WHITE, SEC = "F9F7F5", "BBB1B2"
FONT = "Helvetica Neue"
RADIUS = 0.06  # square-ish: "excessively rounded cards" is on the avoid list
ML = 0.6

prs = Presentation()
prs.slide_width, prs.slide_height = IN(13.333), IN(7.5)
BLANK = prs.slide_layouts[6]


def RGB(h):
    return RGBColor.from_string(h)


def run_style(run, text, pt, color, bold=False):
    run.text = text
    f = run.font
    f.name, f.size, f.bold = FONT, Pt(pt), bold
    f.color.rgb = RGB(color)


def txt(slide, x, y, w, h, paras, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(IN(x), IN(y), IN(w), IN(h))
    tf = box.text_frame
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    tf.vertical_anchor = anchor
    for m in ("margin_left", "margin_right", "margin_top", "margin_bottom"):
        setattr(tf, m, 0)
    for i, p in enumerate(paras):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        para.alignment = p.get("align", PP_ALIGN.LEFT)
        para.line_spacing = p.get("ls", 1.2)
        for r in p["runs"]:
            run_style(para.add_run(), r[0], r[1], r[2], r[3] if len(r) > 3 else False)
    return box


def set_fill_alpha(shp, pct):
    sf = shp._element.spPr.find(
        "{http://schemas.openxmlformats.org/drawingml/2006/main}solidFill")
    clr = sf.find("{http://schemas.openxmlformats.org/drawingml/2006/main}srgbClr")
    clr.append(clr.makeelement(
        "{http://schemas.openxmlformats.org/drawingml/2006/main}alpha",
        {"val": str(int(pct * 1000))}))


def rect(slide, x, y, w, h, fill=None, line=None, line_w=0.75, alpha=None):
    shp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, IN(x), IN(y), IN(w), IN(h))
    if fill:
        shp.fill.solid()
        shp.fill.fore_color.rgb = RGB(fill)
        if alpha is not None:
            sf = shp._element.spPr.find(
                "{http://schemas.openxmlformats.org/drawingml/2006/main}solidFill")
            clr = sf.find("{http://schemas.openxmlformats.org/drawingml/2006/main}srgbClr")
            clr.append(clr.makeelement(
                "{http://schemas.openxmlformats.org/drawingml/2006/main}alpha",
                {"val": str(int(alpha * 1000))}))
    else:
        shp.fill.background()
    if line:
        shp.line.color.rgb = RGB(line)
        shp.line.width = Pt(line_w)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def card(slide, x, y, w, h, fill=BURGUNDY, line=BURNT, alpha=70):
    shp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, IN(x), IN(y), IN(w), IN(h))
    shp.fill.solid()
    shp.fill.fore_color.rgb = RGB(fill)
    set_fill_alpha(shp, alpha)
    shp.line.color.rgb = RGB(line)
    shp.line.width = Pt(0.75)
    shp.shadow.inherit = False
    return shp


def pill(slide, x, y, w, h, fill=None, line=ORANGE, text=None, size=11,
         color=WHITE, bold=True):
    shp = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, IN(x), IN(y), IN(w), IN(h))
    try:
        shp.adjustments[0] = 0.5
    except Exception:
        pass
    if fill:
        shp.fill.solid()
        shp.fill.fore_color.rgb = RGB(fill)
    else:
        shp.fill.background()
    if line:
        shp.line.color.rgb = RGB(line)
        shp.line.width = Pt(1.0)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    if text:
        tf = shp.text_frame
        tf.word_wrap = True
        tf.vertical_anchor = MSO_ANCHOR.MIDDLE
        tf.margin_left = tf.margin_right = IN(0.2)
        tf.margin_top = tf.margin_bottom = 0
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        p.line_spacing = 1.0
        run_style(p.add_run(), text, size, color, bold)
    return shp


def marker(slide, x, y, d=0.16, color=ORANGE):
    rect(slide, x, y, d, d, color)


def plus(slide, x, y, d=0.14, color=ORANGE):
    """Small orange plus marker (style-spec decoration)."""
    rect(slide, x, y + d / 2 - 0.012, d, 0.024, color)
    rect(slide, x + d / 2 - 0.012, y, 0.024, d, color)


def connector(slide, x1, y1, x2, y2, color=BURNT, line_w=0.75):
    from pptx.enum.shapes import MSO_CONNECTOR
    c = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, IN(x1), IN(y1), IN(x2), IN(y2))
    c.line.color.rgb = RGB(color)
    c.line.width = Pt(line_w)
    return c


def brand(slide, page):
    marker(slide, ML, 0.5)
    txt(slide, ML + 0.3, 0.46, 2.6, 0.28,
        [{"runs": [("AI-SLIDE-FORGE", 10, WHITE, True)]}], anchor=MSO_ANCHOR.MIDDLE)
    txt(slide, 12.0, 7.0, 0.75, 0.3,
        [{"runs": [(page, 9, SEC)], "ls": 1.0, "align": PP_ALIGN.RIGHT}])


def new_slide(bg):
    s = prs.slides.add_slide(BLANK)
    s.shapes.add_picture(os.path.join(ASSETS, bg), 0, 0,
                         width=prs.slide_width, height=prs.slide_height)
    return s


